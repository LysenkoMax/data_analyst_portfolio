--------------------------------------------------------------------------------
-- 1. АНАЛИЗ АКТИВНОСТИ ПО ДНЯМ НЕДЕЛИ
-- Цель: Определить пиковые дни нагрузки для планирования маркетинговых акций.
--------------------------------------------------------------------------------

SELECT 
	CASE STRFTIME('%w', order_purchase_timestamp) 
	WHEN '0' THEN '0. Sunday'
	WHEN '1' THEN '1. Monday'
	WHEN '2' THEN '2. Tuesday'
	WHEN '3' THEN '3. Wednesday'
	WHEN '4' THEN '4. Thursday'
	WHEN '5' THEN '5. Friday'
	WHEN '6' THEN '6. Saturday'
	END AS day_of_week, -- Считаем сколько заказов было сделано в каждый из дней недели, конструкция CASE для того чтобы данные были более показательными с названием дня недели.
	-- Перед названием дня недели стоит его порядковый номер (0-Воскресение), для того чтобы при постройке графика компьютером логика не сломалась
	COUNT(customer_id) AS orders_count -- Общее количество заказов в этот день
FROM orders
WHERE order_status = 'delivered' --Отбираем только доставленные заказы
GROUP BY day_of_week --Группипируем по дням недели
ORDER BY 2 DESC;


--------------------------------------------------------------------------------
-- 2. КУЛЬТУРА РАССРОЧКИ (Payment Installments)
-- Цель: Понять, как возможность оплаты по частям влияет на средний чек.
--------------------------------------------------------------------------------

SELECT 
    payment_installments, -- Количество платежей, на которые разбит заказ
    COUNT(order_id) AS orders_count, -- Общее количество заказов в данной группе
    ROUND(AVG(payment_value), 2) AS avg_purchase_value -- Средний чек при таком кол-ве платежей
FROM order_payments
WHERE payment_type = 'credit_card' -- Рассрочка актуальна только для кредитных карт
GROUP BY payment_installments
HAVING orders_count > 100 -- Исключаем редкие выбросы для статистической значимости
ORDER BY payment_installments ASC;

-- ПРИМЕЧАНИЕ: Здесь часто наблюдается рост среднего чека при увеличении числа платежей, 
-- что подтверждает гипотезу о том, что рассрочка стимулирует дорогие покупки.


--------------------------------------------------------------------------------
-- 3. ТОП-10 ПОПУЛЯРНЫХ КАТЕГОРИЙ (с переводом)
-- Цель: Идентификация категорий-драйверов выручки маркетплейса.
--------------------------------------------------------------------------------

SELECT 
    -- Берем английские названия из таблицы-переводчика для международной отчетности
    t.product_category_name_english AS category_name,
    COUNT(oi.order_id) AS units_sold, -- Количество проданных единиц товара
    ROUND(SUM(oi.price), 2) AS total_revenue -- Совокупная выручка категории
FROM order_items oi
-- Соединяем с таблицей продуктов для получения португальских названий категорий
JOIN products p USING(product_id)
-- Соединяем с таблицей-переводчиком для получения английских названий
JOIN product_category_name_translation t USING(product_category_name)
GROUP BY 1 -- Группируем по названию категории
ORDER BY total_revenue DESC -- Сортируем по убыванию выручки
LIMIT 10; -- Ограничиваем список десятью лидерами
